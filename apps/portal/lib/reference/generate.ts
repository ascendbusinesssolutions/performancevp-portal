function literal(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return `'${value.replace(/'/g, "''")}'`;
  if (Array.isArray(value) && value.every((v) => typeof v === "string")) {
    return value.length === 0 ? "'{}'::text[]" : `array[${value.map(literal).join(", ")}]`;
  }
  return `${literal(JSON.stringify(value))}::jsonb`;
}

const HEADER = `-- Generated by apps/portal/lib/reference from the source documents in docs/source-ip
-- (\`pnpm --filter @performancevp/portal reference\`). Do not edit: change the source or the
-- interpretation, regenerate, and let reference.test.ts confirm it. When a source document changes
-- after this migration has been applied, generate a new migration of the same form rather than
-- editing this one.`;

export function migrationSql(set: ReferenceSet, title: string): string {
  const out: string[] = [`-- ${title}`, "--", HEADER, ""];
  for (const spec of TABLES) {
    const rows = spec.rows(set);
    const updates = spec.columns.filter((c) => !spec.key.includes(c));
    out.push(`-- ${spec.table}: ${rows.length} rows.`);
    out.push(`insert into public.${spec.table} (${spec.columns.join(", ")}) values`);
    out.push(
      rows
        .map((row) => `  (${spec.columns.map((c) => literal(field(row, c))).join(", ")})`)
        .join(",\n"),
    );
    out.push(
      updates.length === 0
        ? `on conflict (${spec.key.join(", ")}) do nothing;`
        : `on conflict (${spec.key.join(", ")}) do update set\n  ${updates.map((c) => `${c} = excluded.${c}`).join(",\n  ")};`,
    );
    out.push("");
  }
  // Rows no longer in the source go, children first.
  for (const spec of [...TABLES].reverse()) {
    const rows = spec.rows(set);
    const keyTuple = spec.key.length === 1 ? spec.key[0] : `(${spec.key.join(", ")})`;
    const values = rows
      .map((row) =>
        spec.key.length === 1
          ? literal(field(row, spec.key[0]!))
          : `(${spec.key.map((k) => literal(field(row, k))).join(", ")})`,
      )
      .join(", ");
    out.push(`delete from public.${spec.table} where ${keyTuple} not in (${values});`);
  }
  return `${out.join("\n")}\n`;
}

export function pgtapSql(set: ReferenceSet): string {
  const out: string[] = [
    "-- The reference tables hold exactly the rows generated from the source documents (Milestone 5",
    "-- plan, Section 1.2): the last link of the chain source, JSON, migration, database.",
    "--",
    HEADER,
    "begin;",
    "",
    `select plan(${TABLES.length});`,
    "",
  ];
  for (const spec of TABLES) {
    const expected = spec.rows(set).map((row) => {
      const ordered: Record<string, unknown> = {};
      for (const c of spec.columns) ordered[c] = field(row, c) ?? null;
      return ordered;
    });
    out.push(
      `select set_eq(\n  $$ select to_jsonb(t) from public.${spec.table} t $$,\n  $$ select jsonb_array_elements($json$${JSON.stringify(expected)}$json$::jsonb) $$,\n  '${spec.table} holds exactly the generated rows'\n);`,
    );
    out.push("");
  }
  out.push("select * from finish();", "", "rollback;");
  return `${out.join("\n")}\n`;
}
