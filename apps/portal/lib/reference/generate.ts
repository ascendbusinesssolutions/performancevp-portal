import type { ReferenceSet } from "./types";

/**
 * Writes the reference set as SQL: the data migration (a full upsert, so a later refresh of the
 * source documents becomes a new migration of the same form) and the pgTAP test that proves the
 * loaded tables hold exactly these rows. Both are generated from `reference.json` and checked by
 * `reference.test.ts`; neither is edited by hand.
 */

interface TableSpec {
  table: string;
  key: readonly string[];
  columns: readonly string[];
  rows: (set: ReferenceSet) => readonly object[];
}

function field(row: object, column: string): unknown {
  return (row as Record<string, unknown>)[column];
}

